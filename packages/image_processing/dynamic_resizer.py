"""Dynamic Image Resizer and Resolution Policy Optimizer for VLM Serving."""

from __future__ import annotations

import math
from enum import Enum
from typing import Tuple
from PIL import Image

from packages.telemetry.logging import get_logger

logger = get_logger("dynamic_resizer")


class ResolutionPolicy(str, Enum):
    LOW_768 = "768"        # Fast, low VRAM, good for general VQA
    BALANCED_1024 = "1024"  # Balanced latency/accuracy for standard receipts
    HIGH_1280 = "1280"      # Gold standard for dense invoices and tables
    UNBOUNDED = "original"  # No downsampling (benchmark baseline)
    ADAPTIVE = "adaptive"   # Heuristic: large dense doc -> 1280, simple photo -> 768


class DynamicResizer:
    """Scales image according to resolution policy and computes token/VRAM footprints."""

    PATCH_SIZE = 28  # Qwen2-VL patch size (28x28 spatial merge)

    def __init__(self, policy: ResolutionPolicy = ResolutionPolicy.HIGH_1280) -> None:
        self.policy = policy

    @staticmethod
    def estimate_visual_tokens(width: int, height: int, patch_size: int = 28) -> int:
        """Estimate the number of visual patch tokens generated by vision encoder."""
        grid_w = max(1, math.ceil(width / patch_size))
        grid_h = max(1, math.ceil(height / patch_size))
        return grid_w * grid_h

    @staticmethod
    def estimate_vram_mb(tokens: int, base_vram_mb: float = 4800.0) -> float:
        """Estimate peak VRAM required for KV cache + vision tokens during inference."""
        # Empirical slope from Phase 0: ~0.85 MB per token overhead in FP16/BF16
        return base_vram_mb + (tokens * 0.85)

    def get_target_edge(self, image: Image.Image) -> int | None:
        """Determine maximum long edge size based on policy and image attributes."""
        if self.policy == ResolutionPolicy.LOW_768:
            return 768
        elif self.policy == ResolutionPolicy.BALANCED_1024:
            return 1024
        elif self.policy == ResolutionPolicy.HIGH_1280:
            return 1280
        elif self.policy == ResolutionPolicy.UNBOUNDED:
            return None
        elif self.policy == ResolutionPolicy.ADAPTIVE:
            # If image aspect ratio is extreme or dimensions > 2000, prioritize 1280
            w, h = image.size
            if max(w, h) >= 1600 or (max(w, h) / min(w, h)) > 2.0:
                return 1280
            return 1024
        return 1280

    def optimize_image(self, image: Image.Image) -> Tuple[Image.Image, dict[str, Any]]:
        """Resize image according to policy and return metadata (dimensions, tokens, savings)."""
        orig_w, orig_h = image.size
        orig_tokens = self.estimate_visual_tokens(orig_w, orig_h, self.PATCH_SIZE)

        target_edge = self.get_target_edge(image)
        longest_edge = max(orig_w, orig_h)

        if target_edge is None or longest_edge <= target_edge:
            # No resizing needed
            return image, {
                "original_size": (orig_w, orig_h),
                "optimized_size": (orig_w, orig_h),
                "visual_tokens": orig_tokens,
                "token_reduction_pct": 0.0,
                "policy": str(self.policy),
                "resized": False,
            }

        scale = target_edge / float(longest_edge)
        new_w = max(1, int(round(orig_w * scale)))
        new_h = max(1, int(round(orig_h * scale)))

        resized_img = image.resize((new_w, new_h), Image.Resampling.LANCZOS)
        new_tokens = self.estimate_visual_tokens(new_w, new_h, self.PATCH_SIZE)
        token_reduction = (1.0 - (new_tokens / orig_tokens)) * 100.0

        logger.debug(
            f"Resized image ({orig_w}x{orig_h} -> {new_w}x{new_h}). "
            f"Tokens: {orig_tokens} -> {new_tokens} (-{token_reduction:.1f}%)"
        )

        return resized_img, {
            "original_size": (orig_w, orig_h),
            "optimized_size": (new_w, new_h),
            "visual_tokens": new_tokens,
            "token_reduction_pct": round(token_reduction, 2),
            "policy": str(self.policy),
            "resized": True,
        }
