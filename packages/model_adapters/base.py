"""Abstract base interface for Vision-Language Model adapters."""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Literal
from PIL import Image
from pydantic import BaseModel, Field

from packages.contracts.models import ModelCapabilities

ModelStatusType = Literal["NOT_LOADED", "LOADING", "READY", "ERROR"]


class InferenceResult(BaseModel):
    """Normalized inference output across all model engines."""

    prediction_text: str = Field(description="Generated textual response")
    input_tokens: int = Field(default=0, description="Tokens consumed by prompt + image")
    output_tokens: int = Field(default=0, description="Tokens generated by model")
    preprocessing_ms: float = Field(default=0.0, description="Image and prompt prep duration in ms")
    inference_ms: float = Field(default=0.0, description="Model generation compute duration in ms")
    finish_reason: Literal["stop", "length", "content_filter", "error"] = "stop"
    extra: dict[str, Any] = Field(default_factory=dict, description="Engine-specific telemetry")


class BaseModelAdapter(ABC):
    """Contract for VLM engines (Transformers, vLLM, SGLang, Paddle, etc.)."""

    def __init__(self, model_id: str) -> None:
        self.model_id = model_id
        self._status: ModelStatusType = "NOT_LOADED"
        self._error_message: str | None = None
        self._capabilities = ModelCapabilities()

    @property
    def status(self) -> ModelStatusType:
        return self._status

    @property
    def capabilities(self) -> ModelCapabilities:
        return self._capabilities

    @abstractmethod
    def load(self, config: dict[str, Any] | None = None) -> None:
        """Load model weights, tokenizer, and vision processors into memory/GPU."""

    @abstractmethod
    def infer(
        self,
        prompt: str,
        image: Image.Image | None = None,
        max_tokens: int = 256,
        temperature: float = 0.0,
        **kwargs: Any,
    ) -> InferenceResult:
        """Execute multimodal inference given text prompt and optional image."""

    @abstractmethod
    def unload(self) -> None:
        """Release GPU memory, unload weights, and cleanup resources."""

    def health(self) -> dict[str, Any]:
        """Report adapter health and runtime status."""
        return {
            "model_id": self.model_id,
            "status": self._status,
            "error": self._error_message,
            "capabilities": self._capabilities.model_dump(),
        }
